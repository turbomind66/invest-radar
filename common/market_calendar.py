# 半日交易（感恩节次日、圣诞前日等）：这里简化为「仍算交易日」，不影响调度判定的正确性


def is_a_share_trading_day(d: date = None) -> bool:
    d = d or date.today()
    if d.weekday() >= 5:  # 周六=5 周日=6
        return False
    return d.isoformat() not in A_SHARE_HOLIDAYS


def is_us_trading_day(d: date = None) -> bool:
    d = d or date.today()
    if d.weekday() >= 5:
        return False
    return d.isoformat() not in US_HOLIDAYS


